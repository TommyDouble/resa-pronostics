@lru_cache(maxsize=1)
def get_players() -> tuple:
    """All World Cup players as dicts: name, team, position, club."""
    try:
        with open(PLAYERS_PATH, encoding="utf-8") as f:
            return tuple(json.load(f))
    except Exception:
        logger.warning("players.json introuvable ou invalide — fallback liste réduite.")
        return tuple(
            {"name": name, "team": "", "position": "", "club": ""}
            for name in LEGACY_SCORERS
        )


def scorer_choice(player: dict) -> str:
    """Canonical value stored for a top-scorer pick, unambiguous across teams."""
    if player.get("team"):
        return f"{player['name']} ({player['team']})"
    return player["name"]


@lru_cache(maxsize=1)
def get_scorer_choices() -> tuple:
    """Canonical top-scorer values, sorted by player name."""
    return tuple(sorted(
        (scorer_choice(p) for p in get_players()),
        key=lambda s: s.casefold(),
    ))


@lru_cache(maxsize=1)
def get_players_by_team() -> dict:
    """Players grouped by team (teams sorted alphabetically), attackers first."""
    position_order = {"FW": 0, "MF": 1, "DF": 2, "GK": 3}
    grouped: dict[str, list] = {}
    for player in get_players():
        grouped.setdefault(player.get("team") or "Autres", []).append(player)
    for team_players in grouped.values():
        team_players.sort(key=lambda p: (
            position_order.get(p.get("position", ""), 4),
            p["name"].casefold(),
        ))
    return dict(sorted(grouped.items(), key=lambda kv: kv[0].casefold()))


def is_valid_scorer(value: str) -> bool:
    return value in get_scorer_choices()


def normalize_scorer(value: str) -> str:
    """Map a stored scorer value to its canonical form when unambiguous.

    Older drafts stored the bare player name; canonical values are "Name (Team)".
    Returns the input unchanged when it is already canonical or can't be resolved.
    """
    value = (value or "").strip()
    if not value or is_valid_scorer(value):
        return value
    matches = [p for p in get_players() if p["name"] == value]
    if len(matches) == 1:
        return scorer_choice(matches[0])
    return value
